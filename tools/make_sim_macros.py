METH = {"cov": "Cov", "fixed": "Fixed", "heuristic": "Heur", "ccconst": "Const"}
METH3 = {k: METH[k] for k in ("cov", "fixed", "heuristic")}   # the robustness/ablation campaigns contain 3 controllers
