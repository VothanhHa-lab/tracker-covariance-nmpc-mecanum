    if syn:
        sys.exit("REFUSED: sim_summary.json carries the synthetic flag.")
    out = a.paper / "tables" / "sim_macros.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(M.text())
    n_tbd = sum(chr(92) + "TBD{}" in line for line in M.lines)
    print(f"wrote {out}: {len(M.names)} macros, {n_tbd} still TBD")
